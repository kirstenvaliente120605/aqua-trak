import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schemaPath = path.join(projectRoot, "backend", "schema.sql");
const reportPath = path.join(projectRoot, "station-coords-report.json");
const sql = fs.readFileSync(schemaPath, "utf8");
const seedRows = [...sql.matchAll(/^\s*\('([^']+)',\s*'((?:[^']|'')*)',\s*'([^']*)',\s*'([^']*)',\s*'[^']*',\s*'[^']*',\s*[\d.]+,\s*[\d.]+,\s*[01],\s*(NULL|[-\d.]+),\s*(NULL|[-\d.]+)\)/gm)];
const stations = seedRows.map((match) => ({
  id: match[1],
  name: match[2].replaceAll("''", "'"),
  area: match[3],
  address: match[4],
  lat: match[5] === "NULL" ? null : Number(match[5]),
  lng: match[6] === "NULL" ? null : Number(match[6]),
}));

if (!stations.length) throw new Error(`No station seed rows found in ${schemaPath}`);

const validPoint = ({ lat, lng }) => Number.isFinite(lat) && Number.isFinite(lng) && Math.abs(lat) <= 90 && Math.abs(lng) <= 180;
const metersBetween = (a, b) => {
  const rad = (value) => value * Math.PI / 180;
  const dLat = rad(b.lat - a.lat), dLng = rad(b.lng - a.lng);
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(rad(a.lat)) * Math.cos(rad(b.lat)) * Math.sin(dLng / 2) ** 2;
  return 6371000 * 2 * Math.atan2(Math.sqrt(h), Math.sqrt(1 - h));
};

const apiKey = process.env.GOOGLE_MAPS_API_KEY;
const apply = process.argv.includes("--apply");
const results = [];
for (const station of stations) {
  const needsLookup = !validPoint(station) || String(station.lat).split(".")[1]?.length < 6 || String(station.lng).split(".")[1]?.length < 6;
  if (!needsLookup) {
    results.push({ ...station, newLat: station.lat, newLng: station.lng, distanceMeters: 0, confidence: "not flagged", notes: "At least six decimal places; no issue detected by structural checks." });
    continue;
  }
  if (!apiKey) {
    results.push({ ...station, newLat: null, newLng: null, distanceMeters: null, confidence: "manual review", notes: "GOOGLE_MAPS_API_KEY is unavailable; no coordinate was guessed or changed." });
    continue;
  }

  const query = [station.name, station.address || station.area, "Pagadian City, Zamboanga del Sur, Philippines"].filter(Boolean).join(", ");
  const url = new URL("https://maps.googleapis.com/maps/api/geocode/json");
  url.searchParams.set("address", query);
  url.searchParams.set("key", apiKey);
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Google Geocoding API returned HTTP ${response.status} for ${station.id}`);
  const data = await response.json();
  const candidate = data.status === "OK" ? data.results[0] : null;
  const loc = candidate?.geometry?.location;
  const cityMatch = candidate?.formatted_address?.toLowerCase().includes("pagadian") ?? false;
  const highConfidence = Boolean(candidate && loc && !candidate.partial_match && cityMatch && candidate.geometry.location_type === "ROOFTOP" && validPoint({ lat: loc.lat, lng: loc.lng }));
  results.push({
    ...station,
    query,
    newLat: highConfidence ? Number(loc.lat.toFixed(7)) : null,
    newLng: highConfidence ? Number(loc.lng.toFixed(7)) : null,
    distanceMeters: highConfidence && validPoint(station) ? Number(metersBetween(station, loc).toFixed(1)) : null,
    confidence: highConfidence ? "high (ROOFTOP, Pagadian result, not partial)" : "manual review",
    notes: candidate ? `${candidate.formatted_address}; location_type=${candidate.geometry.location_type}; partial_match=${Boolean(candidate.partial_match)}` : `No usable result (API status: ${data.status}).`,
  });
}

const review = results.filter((item) => item.confidence === "manual review");
const accepted = results.filter((item) => item.newLat !== null && item.confidence.startsWith("high"));
if (apply && accepted.length) {
  const backupPath = `${schemaPath}.coords-backup-${new Date().toISOString().replaceAll(/[:.]/g, "-")}`;
  fs.copyFileSync(schemaPath, backupPath);
  const migration = accepted.map((item) => {
    const oldLat = item.lat === null ? "NULL" : item.lat.toFixed(7);
    const oldLng = item.lng === null ? "NULL" : item.lng.toFixed(7);
    return `UPDATE stations SET lat = ${item.newLat.toFixed(7)}, lng = ${item.newLng.toFixed(7)} WHERE id = '${item.id.replaceAll("'", "''")}' AND lat <=> ${oldLat} AND lng <=> ${oldLng};`;
  }).join("\n");
  fs.writeFileSync(path.join(projectRoot, "backend", "migrations", "005_fix_station_coords.sql"), `-- Generated by scripts/fix-station-coords.mjs; guarded by original coordinates.\n${migration}\n`, "utf8");
  console.log(`Original authoritative seed backed up to ${backupPath}`);
}

fs.writeFileSync(reportPath, `${JSON.stringify({ generatedAt: new Date().toISOString(), source: "backend/schema.sql", applied: apply && accepted.length > 0, stations: results }, null, 2)}\n`, "utf8");
console.log(`Coordinate report: ${reportPath}`);
for (const item of results) {
  const before = item.lat === null || item.lng === null ? "null" : `${item.lat}, ${item.lng}`;
  const after = item.newLat === null ? "pending" : `${item.newLat.toFixed(7)}, ${item.newLng.toFixed(7)}`;
  console.log(`${item.name} | old ${before} | new ${after} | moved ${item.distanceMeters ?? "n/a"} m | ${item.confidence} | ${item.notes}`);
}
if (review.length) console.log(`\n${review.length} station(s) need manual verification. No low-confidence coordinates were applied.`);
